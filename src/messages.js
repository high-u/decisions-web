export const LANGS = Object.keys(messages);

// the text of key in lang
export function translate(lang, key, params = {}) {
  const text = messages[lang][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => params[name] ?? '');
}

// the message of an error of scenario.js; its label is itself a key
export const errorText = (lang, { code, params = {} }) =>
  translate(lang, code, { ...params, label: params.label && translate(lang, params.label) });
